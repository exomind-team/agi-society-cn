import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import fs from 'node:fs'
const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',args:['--no-sandbox']})
const page = await browser.newPage({viewport:{width:1440,height:1000}})
const base = process.env.TEST_BASE || 'http://127.0.0.1:4173'
const errors=[]
page.on('pageerror', e=>errors.push(e.message))
fs.mkdirSync('ops/qa/learning-redesign',{recursive:true})
await page.goto(base+'/learn/map',{waitUntil:'networkidle'})
assert.equal(await page.locator('.knowledge-group').count(),6)
const theory = page.locator('#theory > summary')
await theory.focus(); await page.keyboard.press('Enter')
assert.equal(await page.locator('#theory').getAttribute('open'),'')
await theory.press('Space'); assert.equal(await page.locator('#theory').getAttribute('open'),null)
await theory.press('Enter')
const nested=page.locator('#theory > ul > li > details > summary')
await nested.click()
await page.screenshot({path:'ops/qa/learning-redesign/map-desktop.png',fullPage:true})
await page.locator('.learning-starts a').nth(1).click()
await page.waitForURL('**/learn/try')
await page.goBack(); await page.waitForSelector('#theory[open]')
assert.equal(await page.locator('#theory > ul > li > details[open]').count(),1)
// Follow a real tree link and verify the destination, then browser Back.
await page.locator('#theory .knowledge-overview').first().click()
await page.waitForURL('**/research/')
await page.goBack(); await page.waitForSelector('#theory[open]')
// All details remain usable by touch at a narrow viewport, without horizontal scroll.
await page.setViewportSize({width:390,height:844})
await page.locator('#applications > summary').click()
assert.equal(await page.locator('#applications').getAttribute('open'),'')
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1))
await page.screenshot({path:'ops/qa/learning-redesign/map-mobile.png',fullPage:true})
await page.evaluate(()=>document.documentElement.classList.add('dark'))
await page.screenshot({path:'ops/qa/learning-redesign/map-mobile-dark.png',fullPage:true})
await page.goto(base+'/',{waitUntil:'networkidle'})
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1))
assert.equal(await page.locator('.person-featured').count(),6)
assert.equal(await page.locator('.research-entry').count(),0)
assert.equal(await page.locator('.research-feature').count(),1)
await page.screenshot({path:'ops/qa/learning-redesign/home-mobile.png',fullPage:true})
await page.setViewportSize({width:1440,height:1000})
await page.evaluate(()=>document.documentElement.classList.remove('dark'))
await page.screenshot({path:'ops/qa/learning-redesign/home-desktop.png',fullPage:true})
assert.equal(await page.locator('.people-featured').evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length),3)
await page.goto(base+'/news',{waitUntil:'networkidle'})
assert.equal(await page.locator('.research-entry').count(),5)
assert.deepEqual(errors,[])
await browser.close()
console.log('PASS browser: 6 groups; keyboard Enter/Space; nested collapse; route and browser Back state; 390px width; light/dark screenshots; home hero and 6 people in desktop 3 columns; independent news; no page errors.')
